package cloud.osasoft.dartzvibe.domain.game

import cloud.osasoft.dartzvibe.data.model.GameSession
import cloud.osasoft.dartzvibe.data.model.GameStatus
import cloud.osasoft.dartzvibe.data.model.Leg
import cloud.osasoft.dartzvibe.data.model.Throw
import kotlin.uuid.ExperimentalUuidApi

/**
 * The engine after an undo, plus the result of the last dart replayed into its current turn
 * (null when the turn has no darts). The UI derives bust/bounce/checkout state from that result.
 */
data class RewindResult(
    val engine: GameEngine,
    val lastThrowResult: ThrowResult?,
)

/**
 * Undo, built only on [GameSession] + [GameEngine.fromSession] + [GameEngine.addThrow]/[GameEngine.endTurn],
 * so it works the same in every mode and after a resume.
 *
 * - **Single dart:** rebuild the engine from the turn-start session and replay the turn's darts minus the last.
 *   Anything the removed dart did mid-turn (a Parcheesi knockout phantom) disappears with it.
 * - **Previous turn:** rebuild the leg from scratch by replaying every kept turn (so mode state stored on the leg,
 *   such as Cricket marks, Roulette round and Checkout results, is recomputed and phantoms are regenerated), then
 *   replay the removed turn's darts without ending it, so that player is mid-turn with all their darts.
 *
 * Normal undo never leaves the current leg. Only [rewindTurn] with `crossLegBoundary = true` (the Undo on the
 * leg-won and game-over dialogs) reopens a finished leg or a completed match.
 */
@OptIn(ExperimentalUuidApi::class)
object TurnRewind {

    /**
     * The session as it was when the current turn started: the current leg cut after its last player turn.
     * Phantom turns after it were added by the in-progress turn's darts (a phantom sits *before* the turn that
     * caused it). This is what gets persisted, since in-progress darts are never saved.
     */
    fun turnStartSession(session: GameSession): GameSession {
        val leg = session.currentLeg
        val lastPlayerTurn = leg.turns.indexOfLast { !it.isPhantom }
        val keptTurns = leg.turns.take(lastPlayerTurn + 1)
        if (keptTurns.size == leg.turns.size) return session
        return GameEngineHelper.updateLegInSession(session, leg.copy(turns = keptTurns))
    }

    /** Whether [undo] would do anything: darts in the current turn, or an earlier turn in this leg. */
    fun canUndo(engine: GameEngine): Boolean =
        engine.getCurrentTurnThrows().isNotEmpty() ||
            rewindTurn(engine.toGameSession(), crossLegBoundary = false) != null

    /** Whether the leg-won / game-over dialog Undo ([rewindTurn] across the leg boundary) would succeed. */
    fun canUndoWin(engine: GameEngine): Boolean =
        rewindTurn(engine.toGameSession(), crossLegBoundary = true) != null

    /** Removes the last dart of the current turn or, with no darts, reopens the previous turn of this leg. */
    fun undo(engine: GameEngine): RewindResult? =
        undoLastThrow(engine) ?: rewindTurn(engine.toGameSession(), crossLegBoundary = false)

    /** Removes the last dart of the current turn; null when the turn has no darts. */
    fun undoLastThrow(engine: GameEngine): RewindResult? {
        val throws = engine.getCurrentTurnThrows()
        if (throws.isEmpty()) return null
        val start = GameEngine.fromSession(turnStartSession(engine.toGameSession()))
        return replayThrows(start, throws.dropLast(1))
    }

    /**
     * Reopens the last ended turn with all its darts. Returns null when there is nothing to rewind, or when the
     * stored leg doesn't replay to itself (data saved by an older engine), rather than rewrite history.
     *
     * @param crossLegBoundary false for the normal Undo button: only turns of the current, unfinished leg.
     *   True for the dialog Undo: also reopens the winning turn of a just-won leg or a completed match.
     */
    fun rewindTurn(session: GameSession, crossLegBoundary: Boolean): RewindResult? {
        val start = turnStartSession(session)
        val legIndex = rewindTarget(start, crossLegBoundary) ?: return null
        val leg = start.legs[legIndex]
        val playerTurns = leg.playerTurns
        val reopenedTurn = playerTurns.last()
        val keptTurns = playerTurns.dropLast(1)

        val base = start.copy(
            legs = start.legs.take(legIndex) + Leg(),
            currentLegIndex = legIndex,
            status = GameStatus.IN_PROGRESS,
            finishedAt = null,
            winnerId = null,
        )
        val rebuilt = keptTurns.fold(GameEngine.fromSession(base)) { engine, turn ->
            replayThrows(engine, turn.throws).engine.endTurn().first
        }

        // The phantoms right before the reopened turn were caused by it and are regenerated by its replay
        val expectedTurns = leg.turns.take(leg.turns.indexOfLast { !it.isPhantom })
            .dropLastWhile { it.isPhantom }
        if (rebuilt.toGameSession().currentLeg.turns != expectedTurns) return null

        return replayThrows(rebuilt, reopenedTurn.throws)
    }

    /** Index of the leg whose last turn [rewindTurn] would reopen, or null if there is none. */
    private fun rewindTarget(session: GameSession, crossLegBoundary: Boolean): Int? {
        if (session.status == GameStatus.ABANDONED) return null
        val leg = session.currentLeg
        return when {
            leg.winnerId == null && session.status == GameStatus.IN_PROGRESS ->
                session.currentLegIndex.takeIf { leg.playerTurns.isNotEmpty() }
                    ?: previousWonLeg(session).takeIf { crossLegBoundary }

            // Match won: the winning leg is still the current one
            crossLegBoundary && leg.playerTurns.isNotEmpty() -> session.currentLegIndex

            else -> null
        }
    }

    /** A leg win appends an empty leg; the one before it is the won leg. */
    private fun previousWonLeg(session: GameSession): Int? {
        val index = session.currentLegIndex - 1
        val leg = session.legs.getOrNull(index) ?: return null
        val isFreshLeg = session.currentLeg.turns.isEmpty() && session.legs.size == session.currentLegIndex + 1
        return index.takeIf { isFreshLeg && leg.winnerId != null && leg.playerTurns.isNotEmpty() }
    }

    private fun replayThrows(engine: GameEngine, throws: List<Throw>): RewindResult =
        throws.fold(RewindResult(engine, null)) { acc, throwObj ->
            val (next, result) = acc.engine.addThrow(throwObj.segment, throwObj.multiplier)
            RewindResult(next, result)
        }
}
